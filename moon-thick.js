const fs = require("fs");
const path = require("path");

const WEB = path.join(__dirname, "web");
const content = [
'"use strict";',
'',
'const MoonPhase = (function () {',
'',
'  function render(day, size) {',
'    size = size || 100;',
'    const r = 38, cx = 50, cy = 50;',
'    const illumination = 0.08 + ((day - 1) / 29) * 0.92;  // 8% إلى 100%',
'    const path = buildPath(illumination, r, cx, cy);',
'',
'    let svg = \'<svg viewBox="0 0 100 100" width="\' + size + \'" height="\' + size + \'" xmlns="http://www.w3.org/2000/svg">\';',
'    svg += \'<defs>\';',
'    svg += \'<radialGradient id="m\' + day + \'" cx="35%" cy="30%" r="80%">\';',
'    svg += \'<stop offset="0%" stop-color="#ffffff"/>\';',
'    svg += \'<stop offset="60%" stop-color="#fafafa"/>\';',
'    svg += \'<stop offset="100%" stop-color="#e8e8e8"/>\';',
'    svg += \'</radialGradient>\';',
'    svg += \'<filter id="g\' + day + \'" x="-30%" y="-30%" width="160%" height="160%">\';',
'    svg += \'<feGaussianBlur stdDeviation="0.8" result="b"/>\';',
'    svg += \'<feMerge>\';',
'    svg += \'<feMergeNode in="b"/>\';',
'    svg += \'<feMergeNode in="SourceGraphic"/>\';',
'    svg += \'</feMerge>\';',
'    svg += \'</filter>\';',
'    svg += \'</defs>\';',
'    if (path) {',
'      svg += \'<path d="\' + path + \'" fill="url(#m\' + day + \')" filter="url(#g\' + day + \')"/>\';',
'    }',
'    svg += \'</svg>\';',
'    return svg;',
'  }',
'',
'  function buildPath(illumination, r, cx, cy) {',
'    if (illumination < 0.02) return "";',
'',
'    // بدر كامل',
'    if (illumination >= 0.98) {',
'      return "M " + (cx - r) + "," + cy +',
'             " a " + r + "," + r + " 0 1,0 " + (2*r) + ",0" +',
'             " a " + r + "," + r + " 0 1,0 " + (-2*r) + ",0 Z";',
'    }',
'',
'    // إضاءة → عرض القوس',
'    // عند 0.5: نصف قمر (rx = 0)',
'    // عند 0.08: هلال سميك واضح (rx ≈ 0.75r)',
'    // عند 0.92: هلال مكتمل تقريباً (rx ≈ 0.75r، مقلوب)',
'    //',
'    // المعادلة: rx = r × (1 - 2 × e)^0.7',
'    // الأس 0.7 يجعل الهلال أسمك عند الأطراف',
'    const linearRx = 1 - 2 * illumination;',
'    const rx = r * Math.sign(linearRx) * Math.pow(Math.abs(linearRx), 0.65);',
'',
'    const isGibbous = illumination > 0.5;',
'    const absRx = Math.abs(rx);',
'',
'    if (isGibbous) {',
'      // أكثر من نصف — القوس الداخلي يقطع من اليسار',
'      return "M " + cx + "," + (cy - r) +',
'             " A " + r + "," + r + " 0 0,1 " + cx + "," + (cy + r) +',
'             " A " + absRx + "," + r + " 0 0,1 " + cx + "," + (cy - r) + " Z";',
'    } else {',
'      // أقل من نصف — الهلال على اليمين',
'      return "M " + cx + "," + (cy - r) +',
'             " A " + r + "," + r + " 0 0,1 " + cx + "," + (cy + r) +',
'             " A " + absRx + "," + r + " 0 0,0 " + cx + "," + (cy - r) + " Z";',
'    }',
'  }',
'',
'  return { render: render };',
'',
'})();',
'',
'if (typeof window !== "undefined") {',
'  window.MoonPhase = MoonPhase;',
'}',
''
].join("\n");

fs.writeFileSync(path.join(WEB, "moon.js"), content, "utf8");
console.log("✓ moon.js: هلال أسمك (معادلة جديدة)");
